// The battle with this ID, or nullptr.
static Battle* pit_find_battle(int battleID) {
    BattleArea* area = &gBattleAreas[(battleID >> 8) & 0x3F];

    if (area->battles == nullptr) {
        return nullptr;
    }
    return &(*area->battles)[battleID & 0xFF];
}

// The animation a battle part plays when nothing is wrong with it.
static s32 pit_part_idle_anim(const ActorPartBlueprint* part) {
    const s32* anims = part->idleAnimations;

    if (anims == nullptr) {
        return 0;
    }
    for (; anims[0] != STATUS_END; anims += 2) {
        if (anims[0] == STATUS_KEY_NORMAL) {
            return anims[1];
        }
    }
    return 0;
}

static int pit_abs(int value) {
    return value < 0 ? -value : value;
}

static int pit_clamp(int value, int low, int high) {
    return value < low ? low : (value > high ? high : value);
}

// Works out how the first enemy of a battle should look in the overworld.
//   anims  - 16 animation IDs, in the order of NpcData::animations
//   height, radius, level - for the overworld NPC settings
// Returns 0 (leaving everything untouched) if the battle has no usable enemy.
//
// The enemy's battle sprite is the same sprite its overworld NPC uses, so the battle idle animation identifies
// the right row of the table above. A row is chosen if it has the same idle animation, or failing that the same
// sprite and palette. If there is none, the battle idle animation is used for every animation slot.
int pit_enemy_look(int battleID, int* anims, int* height, int* radius, int* level) {
    Battle* battle = pit_find_battle(battleID);
    const ActorBlueprint* actor = nullptr;
    s32 idle = 0;
    s32 i;
    s32 pick = -1;

    if (battle == nullptr || battle->formation == nullptr) {
        return 0;
    }
    for (i = 0; i < battle->formationSize && actor == nullptr; i++) {
        const ActorBlueprint* candidate = (*battle->formation)[i].actor;
        s32 p;

        if (candidate == nullptr || candidate->partsData == nullptr) {
            continue;
        }
        for (p = 0; p < candidate->partCount && idle == 0; p++) {
            idle = pit_part_idle_anim(&candidate->partsData[p]);
        }
        if (idle != 0) {
            actor = candidate;
        }
    }
    if (actor == nullptr) {
        return 0;
    }

    for (i = 0; i < (s32) ARRAY_COUNT(sPitLooks); i++) {
        if (sPitLooks[i].idle == idle) {
            pick = i;
            break;
        }
    }
    if (pick < 0) {
        for (i = 0; i < (s32) ARRAY_COUNT(sPitLooks); i++) {
            if ((sPitLooks[i].idle >> 8) == (idle >> 8)) {
                pick = i;
                break;
            }
        }
    }

    if (pick >= 0) {
        memcpy(anims, &sPitLooks[pick], 16 * sizeof(s32));
    } else {
        for (i = 0; i < 16; i++) {
            anims[i] = idle;
        }
    }
    *height = pit_clamp(pit_abs(actor->size.y), 20, 60);
    *radius = pit_clamp(pit_abs(actor->size.x) / 2, 23, 45);
    *level = actor->level;
    return 1;
}
